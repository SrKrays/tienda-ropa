// interpolación lineal sobre una polilínea [[k, v], ...] (extiende con el primer/último valor)
export function lerpLine(line, k) {
  if (k <= line[0][0]) return line[0][1]
  for (let i = 1; i < line.length; i++) {
    const [k1, v1] = line[i]
    if (k <= k1) {
      const [k0, v0] = line[i - 1]
      return v0 + ((v1 - v0) * (k - k0)) / (k1 - k0)
    }
  }
  return line[line.length - 1][1]
}
